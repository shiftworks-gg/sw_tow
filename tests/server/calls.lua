local test = require 'test'
local flow = require 'flow'
local World = require 'world'
local vector = require 'vector'

test.suite('server › calls')

local FAR = World.FAR

---An owner standing next to their car far from the yard, and a worker on shift.
local function setup(options)
    options = options or {}
    -- Only the calls under test: no NPC contracts or abandoned-vehicle calls appearing on their own.
    options.config = function(config)
        config.contracts.enabled = false
        config.abandoned.enabled = false
    end
    local w = newWorld(options)
    local worker = flow.worker(w)
    local owner = w:addPlayer({ coords = FAR, bank = 5000 })
    local car, vehicleId = w:ownedVehicle(owner, { coords = FAR })
    return w, worker, owner, car, vehicleId
end

test.case('an owner calls a tow; everyone on shift is told', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car, 'Flat tyre')
    test.truthy(w:noticed(owner, 'calls.created'), 'caller told')
    test.truthy(w:noticed(worker, 'calls.new_player'), 'worker told')
    local list = flow.calls(w, worker)
    test.eq(#list, 1)
    test.eq(list[1].type, 'player')
    test.eq(list[1].message, 'Flat tyre')
    test.eq(list[1].plate, w:entity(car).plate)
    w:assertNoErrors()
end)

test.case('refused: no vehicle, vehicle too far away, NPC vehicle, someone else\'s vehicle', function()
    local w, _, owner, car = setup()
    w:command('calltow', owner, {})
    test.truthy(w:noticed(owner, 'calls.no_vehicle'), 'never sat in a vehicle')

    w:clearSent()
    w:advance(2)
    w:enterVehicle(owner, car)
    w:leaveVehicle(owner)
    w:teleport(owner, FAR + vector.vec3(50, 0, 0))
    w:command('calltow', owner, {})
    test.truthy(w:noticed(owner, 'calls.no_vehicle'), '50 m away')

    w:clearSent()
    w:advance(2)
    local npc = w:createVehicle({ model = 'asea', coords = FAR + vector.vec3(10, 10, 0) })
    flow.callTow(w, owner, npc)
    test.truthy(w:noticed(owner, 'calls.not_owner'), 'NPC vehicle')

    w:clearSent()
    w:advance(2)
    local stranger = w:addPlayer({ coords = FAR })
    local theirs = w:ownedVehicle(stranger, { coords = FAR + vector.vec3(-10, 0, 0) })
    flow.callTow(w, owner, theirs)
    test.truthy(w:noticed(owner, 'calls.not_owner'), 'another player\'s vehicle')
    w:assertNoErrors()
end)

test.case('without a garage script there are no player calls', function()
    local w, _, owner, car = setup({ adapters = { garage = 'none' } })
    flow.callTow(w, owner, car)
    test.truthy(w:noticed(owner, 'calls.unavailable'))
end)

test.case('one open call per player, a cooldown, and a server-wide limit', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car)
    w:advance(2)
    w:command('canceltow', owner, {})
    test.truthy(w:noticed(owner, 'calls.cancelled'))
    w:advance(2)
    flow.callTow(w, owner, car)
    test.truthy(w:noticed(owner, 'calls.cooldown'), 'cooldown after the first call')

    w:clearSent()
    w:advance(61)
    flow.callTow(w, owner, car)
    test.truthy(w:noticed(owner, 'calls.created'))
    w:advance(61)
    flow.callTow(w, owner, car)
    test.truthy(w:noticed(owner, 'calls.already_open'))

    local calls = w:module('server.calls')
    for i = 1, 9 do calls.add({ type = 'contract', plate = 'C' .. i, coords = FAR, message = '' }) end
    local other = w:addPlayer({ coords = FAR })
    local otherCar = w:ownedVehicle(other, { coords = FAR + vector.vec3(0, 8, 0) })
    flow.callTow(w, other, otherCar)
    test.truthy(w:noticed(other, 'calls.busy'), 'ten open calls on the server')
    test.eq(#flow.calls(w, worker), 10)
end)

test.case('cancelling: allowed until the vehicle is loaded', function()
    local w, worker, owner, car = setup()
    w:command('canceltow', owner, {})
    test.truthy(w:noticed(owner, 'calls.none_open'))

    flow.callTow(w, owner, car)
    test.accepted(w:call('sw_tow:server:acceptCall', worker, flow.callId(w, worker, 'player')))
    local truck = flow.truck(w, worker, 1)
    flow.drive(w, worker, truck, FAR + vector.vec3(0, 12, 0))
    test.accepted(flow.load(w, worker, truck, car))
    w:clearSent()
    w:command('canceltow', owner, {})
    test.truthy(w:noticed(owner, 'calls.cancel_loaded'))
    test.eq(#flow.calls(w, worker), 1, 'the call stays')
end)

test.case('accepting: only on shift, one call at a time, first come first served', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car)
    local id = flow.callId(w, worker, 'player')
    local idle = w:addPlayer({ job = 'tow' })
    test.refused(w:call('sw_tow:server:acceptCall', idle, id))
    test.eq(#w:call('sw_tow:server:listCalls', idle), 0, 'off shift: no list')

    test.accepted(w:call('sw_tow:server:acceptCall', worker, id))
    test.truthy(w:noticed(owner, 'calls.accepted'), 'caller told')

    local second = flow.worker(w)
    w:advance(2)
    test.refusedWith('calls.taken', w:call('sw_tow:server:acceptCall', second, id))

    w:module('server.calls').add({ type = 'contract', plate = 'C1', coords = FAR, message = '' })
    w:advance(2)
    test.refusedWith('calls.one_at_a_time', w:call('sw_tow:server:acceptCall', worker, flow.callId(w, worker, 'contract')))
end)

test.case('a worker can drop a call; it opens again for others', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car)
    local id = flow.callId(w, worker, 'player')
    test.accepted(w:call('sw_tow:server:acceptCall', worker, id))
    local other = flow.worker(w)
    test.eq(#flow.calls(w, other), 0, 'taken calls are hidden from others')
    test.accepted(w:call('sw_tow:server:dropCall', worker, id))
    test.truthy(w:noticed(owner, 'calls.reopened'))
    test.eq(#flow.calls(w, other), 1)
    test.refused(w:call('sw_tow:server:dropCall', other, id))
end)

test.case('a loaded call cannot be dropped (it could not be delivered any more)', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car)
    local id = flow.callId(w, worker, 'player')
    test.accepted(w:call('sw_tow:server:acceptCall', worker, id))
    local truck = flow.truck(w, worker, 1)
    flow.drive(w, worker, truck, FAR + vector.vec3(0, 12, 0))
    test.accepted(flow.load(w, worker, truck, car))
    test.refusedWith('calls.drop_loaded', w:call('sw_tow:server:dropCall', worker, id))
end)

test.case('open calls expire after 10 minutes, accepted ones after 30', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car)
    w:advance(9 * 60)
    test.eq(#flow.calls(w, worker), 1, 'still open after 9 minutes')
    w:advance(2 * 60)
    test.eq(#flow.calls(w, worker), 0, 'expired after 11 minutes')
    test.truthy(w:noticed(owner, 'calls.expired'))

    w:advance(61)
    flow.callTow(w, owner, car)
    local id = flow.callId(w, worker, 'player')
    test.accepted(w:call('sw_tow:server:acceptCall', worker, id))
    w:advance(29 * 60)
    test.eq(#flow.calls(w, worker), 1, 'accepted: still there after 29 minutes')
    w:advance(2 * 60)
    test.eq(#flow.calls(w, worker), 0, 'accepted: expired after 31 minutes')
    test.eq(#w:sent(worker, 'sw_tow:client:callClosed'), 1, 'worker told to clear the route')
end)

test.case('a call closes when its vehicle disappears', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car)
    w:removeEntity(car)
    w:advance(31)
    test.eq(#flow.calls(w, worker), 0)
    test.truthy(w:noticed(owner, 'calls.vehicle_gone'))
end)

test.case('the end of a shift opens the worker\'s call again', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car)
    test.accepted(w:call('sw_tow:server:acceptCall', worker, flow.callId(w, worker, 'player')))
    w:setJob(worker, 'unemployed')
    local other = flow.worker(w)
    test.eq(#flow.calls(w, other), 1)
    test.truthy(w:noticed(owner, 'calls.reopened'))
end)

test.case('a caller who leaves: open call removed, loaded call kept for the worker', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car)
    w:drop(owner)
    test.eq(#flow.calls(w, worker), 0, 'open call removed')

    local owner2 = w:addPlayer({ coords = FAR })
    local car2 = w:ownedVehicle(owner2, { coords = FAR })
    flow.callTow(w, owner2, car2)
    test.accepted(w:call('sw_tow:server:acceptCall', worker, flow.callId(w, worker, 'player')))
    local truck = flow.truck(w, worker, 1)
    flow.drive(w, worker, truck, FAR + vector.vec3(0, 12, 0))
    test.accepted(flow.load(w, worker, truck, car2))
    w:drop(owner2)
    test.eq(#flow.calls(w, worker), 1, 'loaded call kept')
    w:advance(60)
    flow.drive(w, worker, truck, World.YARD)
    test.accepted(flow.deliver(w, worker, truck))
    w:assertNoErrors()
end)

test.case('other scripts can create calls through the CreateCall export', function()
    local w, worker, owner, car = setup()
    w:enterVehicle(owner, car)
    local ok = w:runNow(w.exported.CreateCall, owner, 'From the phone')
    test.truthy(ok)
    test.eq(flow.calls(w, worker)[1].message, 'From the phone')
end)

test.case('call messages are cut to 120 characters', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car, string.rep('x', 500))
    test.eq(#flow.calls(w, worker)[1].message, 120)
end)

test.case('an accepted call does not expire while its vehicle is on the truck', function()
    local w, worker, owner, car = setup()
    flow.callTow(w, owner, car)
    test.accepted(w:call('sw_tow:server:acceptCall', worker, flow.callId(w, worker, 'player')))
    local truck = flow.truck(w, worker, 1)
    flow.drive(w, worker, truck, FAR + vector.vec3(0, 12, 0))
    test.accepted(flow.load(w, worker, truck, car))
    w:advance(45 * 60)
    test.eq(#flow.calls(w, worker), 1, 'still there after 45 minutes')
    flow.drive(w, worker, truck, World.YARD)
    test.accepted(flow.deliver(w, worker, truck))
end)
