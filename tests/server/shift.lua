test.case('end shift with a truck: only at the truck spot, empty, with the worker next to it', function()
    local w = newWorld()
    local src = flow.worker(w)
    local truck = flow.truck(w, src, 1)
    flow.drive(w, src, truck, World.FAR)
    w:advance(1)
    test.refusedWith('garage.too_far', w:call('sw_tow:server:endShift', src))

    flow.drive(w, src, truck, World.TRUCK_SPAWN)
    w:teleport(src, World.FAR)
    w:advance(1)
    test.refusedWith('garage.too_far', w:call('sw_tow:server:endShift', src)) -- the worker walked away from it

    w:teleport(src, World.TRUCK_SPAWN + vector.vec3(3, 0, 0))
    w.env.Entity(truck).state:set('sw_tow:cargo', 1, true)
    w:advance(1)
    test.refusedWith('garage.has_cargo', w:call('sw_tow:server:endShift', src))
    w.env.Entity(truck).state:set('sw_tow:cargo', nil, true)

    w:advance(1)
    test.accepted(w:call('sw_tow:server:endShift', src))
    test.falsy(w:exists(truck), 'truck handed in')
    test.eq(w.env.Player(src).state['sw_tow:shift'], false, 'shift over')
    w:assertNoErrors()
end)

-- Deposit and pay collected at the office (the shipped defaults).
local function officePay(config)
    config.garage.deposit = 500
    config.garage.damageFromDeposit = true
    config.payout.collect = 'office'
end

test.case('deposit: taken with the truck, refused without the money, paid back in full for an undamaged truck', function()
    local w = newWorld({ config = officePay })
    local poor = flow.worker(w, { cash = 100, bank = 300 })
    w:teleport(poor, World.OFFICE)
    test.refusedWith('garage.no_deposit', w:call('sw_tow:server:takeTruck', poor, 1))
    test.eq(w:money(poor, 'cash') + w:money(poor, 'bank'), 400, 'nothing taken')

    local src = flow.worker(w, { cash = 200, bank = 1000 })
    local truck = flow.truck(w, src, 1)
    test.eq(w:money(src, 'cash'), 200, 'cash too little: all from the bank')
    test.eq(w:money(src, 'bank'), 500, 'deposit taken from the bank')

    flow.drive(w, src, truck, World.TRUCK_SPAWN)
    w:teleport(src, World.TRUCK_SPAWN + vector.vec3(3, 0, 0))
    w:advance(1)
    test.accepted(w:call('sw_tow:server:endShift', src))
    test.eq(w:money(src, 'bank'), 1000, 'deposit back')
    w:assertNoErrors()
end)

test.case('deposit: damage comes off it, a truck left out keeps it', function()
    local w = newWorld({ config = officePay })
    local src = flow.worker(w, { bank = 2000 })
    local truck = flow.truck(w, src, 1)
    w:entity(truck).body = 600.0
    flow.drive(w, src, truck, World.TRUCK_SPAWN)
    w:teleport(src, World.TRUCK_SPAWN + vector.vec3(3, 0, 0))
    w:advance(1)
    test.accepted(w:call('sw_tow:server:returnTruck', src))
    test.eq(w:money(src, 'bank'), 2000 - 500 + 300, '60% of the deposit back')

    w:advance(6)
    truck = flow.truck(w, src, 1)
    flow.drive(w, src, truck, World.FAR)
    w:teleport(src, World.OFFICE)
    w:advance(1)
    test.accepted(w:call('sw_tow:server:clockOut', src))
    test.falsy(w:exists(truck), 'truck removed')
    test.eq(w:money(src, 'bank'), 2000 - 500 + 300 - 500, 'deposit kept')
    w:assertNoErrors()
end)

test.case('deposit: a new truck at the counter keeps the deposit of the old one', function()
    local w = newWorld({ config = officePay })
    local src = flow.worker(w, { bank = 2000 })
    local old = flow.truck(w, src, 1)
    flow.drive(w, src, old, World.FAR)
    w:teleport(src, World.OFFICE)
    w:advance(6)
    test.refusedWith('garage.already_out', w:call('sw_tow:server:takeTruck', src, 1))
    w:advance(6)
    local ok, netId = w:call('sw_tow:server:takeTruck', src, 1, true)
    test.accepted(ok, netId)
    test.falsy(w:exists(old), 'old truck removed')
    test.eq(w:money(src, 'bank'), 1000, 'two deposits paid, the first one kept')
    w:assertNoErrors()
end)

test.case('deposit: a truck removed in working order comes back, a cleared wreck does not', function()
    local w = newWorld({ config = officePay })
    local src = flow.worker(w, { bank = 2000 })
    local truck = flow.truck(w, src, 1)
    w:removeEntity(truck)
    test.eq(w:money(src, 'bank'), 2000, 'removed by the game in working order: deposit back')

    w:advance(6)
    truck = flow.truck(w, src, 1)
    w:entity(truck).engine = -4000.0
    w:advance(11)
    w:removeEntity(truck)
    test.eq(w:money(src, 'bank'), 1500, 'wreck cleared: deposit kept')
end)

test.case('pay at the office: delivery pay adds up and is paid when the shift ends', function()
    local w = newWorld({ config = officePay })
    local worker = flow.worker(w, { bank = 1000 })
    local t = flow.towedToYard(w, { worker = worker })
    test.accepted(flow.deliver(w, t.worker, t.truck))
    test.eq(w:money(worker, 'bank'), 500, 'only the deposit left the account')
    test.truthy(w:noticed(worker, 'impound.earned'), 'told it is added to the shift pay')

    flow.drive(w, worker, t.truck, World.TRUCK_SPAWN)
    w:teleport(worker, World.TRUCK_SPAWN + vector.vec3(3, 0, 0))
    w:advance(1)
    test.accepted(w:call('sw_tow:server:endShift', worker))
    test.eq(w:money(worker, 'bank'), 1000 + 201, 'deposit back and the pay')
    test.truthy(w:noticed(worker, 'shift.paid'), 'told the pay')
    w:assertNoErrors()
end)

test.case('pay at the office: a disconnect keeps the pay and the deposit for the next shift', function()
    local w = newWorld({ config = officePay })
    local worker = flow.worker(w, { bank = 1000 })
    local citizenid = w.players[worker].citizenid
    local t = flow.towedToYard(w, { worker = worker })
    test.accepted(flow.deliver(w, t.worker, t.truck))
    w:drop(worker)
    test.eq(w.owed[citizenid], 201 + 500, 'pay and deposit owed')

    local back = w:addPlayer({ job = 'tow', citizenid = citizenid, bank = 0 })
    test.accepted(flow.clockIn(w, back))
    test.eq(w:money(back, 'bank'), 701, 'paid on the next clock in')
    test.truthy(w:noticed(back, 'shift.paid_earlier'))
    w:assertNoErrors()
end)

test.case('a restart owes every deposit back; it is paid at the next clock in', function()
    local w = newWorld({ config = function(config) config.garage.deposit = 500 end })
    local src = flow.worker(w, { bank = 1000 })
    flow.truck(w, src, 1)
    w:trigger('onResourceStop', nil, 'sw_tow')
    test.eq(w.owed[w.players[src].citizenid], 500)
end)
