test.case('a truck removed by something else: the worker is told and every action says so', function()
    local w = newWorld()
    local src = flow.worker(w)
    local truck = flow.truck(w, src, 1)
    local truckNet = w:entity(truck).net
    flow.drive(w, src, truck, World.FAR)
    w:clearSent()
    w:removeEntity(truck)
    test.eq(#w:sent(src, 'sw_tow:client:truckLost'), 1, 'truckLost sent once')

    -- A client that still shows the truck gets the reason, not "something went wrong".
    local car = w:createVehicle({ model = 'asea', coords = World.FAR + vector.vec3(0, -10, 0) })
    w:advance(1)
    test.refusedWith('garage.lost', w:call('sw_tow:server:attach', src, truckNet, w:entity(car).net))
    test.refusedWith('garage.lost', w:call('sw_tow:server:secured', src, truckNet))
    test.refusedWith('garage.lost', w:call('sw_tow:server:ramps', src, truckNet, false))
    w:assertNoErrors()
end)

test.case('returning, clocking out and resource stop do not count as a lost truck', function()
