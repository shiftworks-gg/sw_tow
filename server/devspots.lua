---Developer tool for NPC contract spots. Admins only (ace `command.swtow_spots`).
---  swtow_spots generate [cell]  scan the map from your client, save data/spots.generated.lua
---  swtow_spots show | hide      draw every spot on your map (blue: bundled, orange: generated)
---Generated spots are used after `restart sw_tow`. Delete the file to go back to the bundled list.
local config = require 'config'
local spotlist = require 'server.spotlist'

local FILE = 'data/spots.generated.lua'
local SPACING = 150.0     -- Minimum distance between any two spots.
local KEEP_CLEAR = 120.0  -- Minimum distance from the office and every yard.

---Places a contract must never spawn: the tow company's own grounds.
local function protectedPlaces()
    local places = { config.office.coords.xyz }
    for _, yard in pairs(config.yards) do
        places[#places + 1] = yard.zone and yard.zone.coords or yard.coords
    end
    return places
end

---@param point vector3
---@param list vector3[]
---@param distance number
local function near(point, list, distance)
    for i = 1, #list do
        if #(point - list[i].xyz) < distance then return true end
    end
    return false
end

---@param src integer
---@param sampled table[]
---@return vector4[] kept
local function filter(src, sampled)
    local taken = {}
    for i = 1, #spotlist.bundled do taken[#taken + 1] = spotlist.bundled[i] end
    local places = protectedPlaces()
    local kept = {}

    for i = 1, #sampled do
        local s = sampled[i]
        if type(s) == 'vector4' and s.x == s.x and s.y == s.y then  -- s.x == s.x rejects NaN
            local point = s.xyz
            if not near(point, places, KEEP_CLEAR) and not near(point, taken, SPACING) then
                kept[#kept + 1] = s
                taken[#taken + 1] = point
            end
        end
    end

    lib.print.info(('%s: %d sampled, %d kept'):format(GetPlayerName(src), #sampled, #kept))
    return kept
end

---@param spots vector4[]
local function save(spots)
    local lines = {
        '---Generated by `swtow_spots generate` on ' .. os.date('!%Y-%m-%d %H:%M UTC') .. '. Server-side only.',
        '---Spots on the right road edge, facing along the road. Delete a line to drop a spot.',
        'return {',
    }
    for i = 1, #spots do
        local s = spots[i]
        lines[#lines + 1] = ('    vec4(%.2f, %.2f, %.2f, %.1f),'):format(s.x, s.y, s.z, s.w)
    end
    lines[#lines + 1] = '}'
    lines[#lines + 1] = ''
    local text = table.concat(lines, '\n')
    return SaveResourceFile(cache.resource, FILE, text, #text)
end

local generating = false

local actions = {}

function actions.generate(src, args)
    if generating then
        return TriggerClientEvent('sw_tow:client:notify', src, 'A scan is already running.', 'warning')
    end
    local cell = math.floor(tonumber(args[2]) or 250)
    if cell < 100 or cell > 1000 then
        return TriggerClientEvent('sw_tow:client:notify', src, 'Cell size must be 100 to 1000 metres.', 'error')
    end

    generating = true
    TriggerClientEvent('sw_tow:client:notify', src, ('Scanning the map in %d m cells. Stay in game.'):format(cell), 'inform')
    local ok, sampled = pcall(lib.callback.await, 'sw_tow:dev:sampleSpots', src, cell)
    generating = false
    if not ok or type(sampled) ~= 'table' then
        return TriggerClientEvent('sw_tow:client:notify', src, 'The scan failed. See the server console.', 'error')
    end

    local kept = filter(src, sampled)
    if #kept == 0 then
        return TriggerClientEvent('sw_tow:client:notify', src, 'No new spots found.', 'warning')
    end
    if not save(kept) then
        return TriggerClientEvent('sw_tow:client:notify', src, ('Could not write %s.'):format(FILE), 'error')
    end
    TriggerClientEvent('sw_tow:client:notify', src,
        ('%d spots saved to %s. Check them with "swtow_spots show", then restart sw_tow.'):format(#kept, FILE), 'success')
end

function actions.show(src)
    local list = {}
    for i = 1, #spotlist.bundled do
        local s = spotlist.bundled[i]
        list[#list + 1] = { x = s.x, y = s.y, z = s.z }
    end
    -- Read the file again, so spots generated since the last restart show too.
    local generated = spotlist.readGenerated()
    for i = 1, #generated do
        local s = generated[i]
        list[#list + 1] = { x = s.x, y = s.y, z = s.z, generated = true }
    end
    TriggerClientEvent('sw_tow:dev:showSpots', src, list)
    TriggerClientEvent('sw_tow:client:notify', src,
        ('%d bundled and %d generated spots on the map.'):format(#spotlist.bundled, #generated), 'inform')
end

function actions.hide(src)
    TriggerClientEvent('sw_tow:dev:hideSpots', src)
end

RegisterCommand('swtow_spots', function(src, args)
    if src == 0 then
        return print('swtow_spots works from the game only: the scan runs on your client.')
    end
    local action = actions[args[1] or '']
    if not action then
        return TriggerClientEvent('sw_tow:client:notify', src, 'Usage: swtow_spots generate [cell] | show | hide', 'inform')
    end
    action(src, args)
end, true)
